function createIdleAnimation(scene, animationKey, textureKey, endFrame, frameRate = 6) {
  if (!scene.anims.exists(animationKey)) {
    scene.anims.create({
      key: animationKey,
      frames: scene.anims.generateFrameNumbers(textureKey, {
        start: 0,
        end: endFrame,
      }),
      frameRate,
      repeat: -1,
    });
  }
}

